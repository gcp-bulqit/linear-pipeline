# STAGES: author this section. One stage() per step the human takes.
# ──────────────────────────────────────────────────────────────────────────

TOTAL_STAGES=9

# The framework lives wherever this script does; the target is the cwd.
FRAMEWORK_REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TARGET_REPO="$PWD"
SKILL_SRC="$FRAMEWORK_REPO/.claude/skills/linear-pipeline"
SKILL_DST="$TARGET_REPO/.claude/skills/linear-pipeline"
LINEAR_MCP_SERVER="${LINEAR_MCP_SERVER:-linear-bot}"

banner "Linear Pipeline: onboard a repository"

# ── 1 ─────────────────────────────────────────────────────────────────────
stage "Preflight"
say "Installing the Linear pipeline into the repository you are standing in."
note "framework: $FRAMEWORK_REPO"
note "target:    $TARGET_REPO"
printf '\n'

if [[ "$FRAMEWORK_REPO" == "$TARGET_REPO" ]]; then
  warn "You are in the framework repo itself. cd to the target repository first."
  exit 1
fi
[[ -f "$SKILL_SRC/SKILL.md" ]] || { warn "No skill found at $SKILL_SRC; is this script inside the framework repo?"; exit 1; }
git -C "$TARGET_REPO" rev-parse --is-inside-work-tree >/dev/null 2>&1 || {
  warn "$TARGET_REPO is not a git repository. The pipeline needs one (worktrees, branches, PRs)."
  exit 1
}
command -v python3 >/dev/null 2>&1 || { warn "python3 is required by the pipeline's scripts."; exit 1; }
python3 -c 'import sys; sys.exit(0 if sys.version_info >= (3, 8) else 1)' || {
  warn "python3 3.8 or later is required."; exit 1;
}
say "✓ git repository"
say "✓ python3 $(python3 -c 'import sys;print(".".join(map(str,sys.version_info[:2])))')"

if command -v gh >/dev/null 2>&1 && gh auth status >/dev/null 2>&1; then
  say "✓ gh authenticated"
else
  warn "gh is not authenticated. The pipeline opens pull requests with it."
  SKIPPED+=("gh auth login — needed before the pipeline can open a PR")
fi
if command -v claude >/dev/null 2>&1; then say "✓ claude CLI"; else
  warn "claude CLI not on PATH; stage 5 needs it."
fi
printf '\n'
confirm "Install into $TARGET_REPO?" || { say "Nothing changed."; exit 0; }

# ── 2 ─────────────────────────────────────────────────────────────────────
stage "Linear: the Pipeline Bot user"
say "The pipeline needs its own Linear identity, separate from yours."
note "Its authorship is how a teammate tells a machine comment from a person's,"
note "and how the pipeline recognises a human reply to one of its questions."
printf '\n'
open_url "https://linear.app/settings/members"
step "Invite or locate a dedicated member for the bot (e.g. 'Pipeline Bot')."
step "Copy its name as Linear shows it — issues assigned to it become the pipeline's queue."
ask LINEAR_BOT_USER "Bot user (name as Linear shows it):"
[[ -n "$LINEAR_BOT_USER" ]] || { warn "A bot user is required."; exit 1; }
write_env LINEAR_BOT_USER "$LINEAR_BOT_USER"

# ── 3 ─────────────────────────────────────────────────────────────────────
stage "Linear: the bot's read-scoped API key"
say "Ticket bodies are fetched with this key, by a script that writes them to a"
say "file — so a ticket's prose never enters the supervisor's context window."
printf '\n'
warn "Sign in to Linear AS THE BOT before creating this key, not as yourself."
pause "Press Enter once you are signed in as the bot"
open_url "https://linear.app/settings/api"
step "Personal API keys → Create key."
step "Give it READ scope only. The pipeline never writes to Linear with this key."
ask_secret LINEAR_API_KEY "Paste the key (hidden):"
[[ -n "$LINEAR_API_KEY" ]] || { warn "The key is required."; exit 1; }
write_env LINEAR_API_KEY "$LINEAR_API_KEY"
note "Stored in $ENV_FILE. Keep it out of .agent/config.json, which is committed."
if git -C "$TARGET_REPO" check-ignore -q "$ENV_FILE" 2>/dev/null; then
  say "✓ $ENV_FILE is gitignored"
else
  warn "$ENV_FILE is NOT gitignored. Stage 7 adds it; do not commit before then."
fi
note "The pipeline reads LINEAR_API_KEY from the environment. Export it (or load"
note "$ENV_FILE with your usual tool) in the shell you start Claude Code from."

# ── 4 ─────────────────────────────────────────────────────────────────────
stage "Document the key for the next person"
if [[ -f .env.example ]]; then
  if grep -qE '^LINEAR_API_KEY=' .env.example; then
    say "✓ .env.example already documents LINEAR_API_KEY"
  else
    printf '\n# Linear pipeline: the Pipeline Bot read-scoped API key.\nLINEAR_API_KEY=\n' >> .env.example
    say "✓ appended LINEAR_API_KEY to .env.example (name only, no value)"
  fi
else
  note "no .env.example in this repo; skipping"
fi

# ── 5 ─────────────────────────────────────────────────────────────────────
stage "The bot's MCP server entry"
say "Linear writes go through MCP, authenticated as the bot. That entry is a"
say "separate identity from your own Linear connection, which stays untouched."
printf '\n'
step "Run this in another terminal, from $TARGET_REPO:"
note "  claude mcp add --transport http linear-bot https://mcp.linear.app/mcp"
step "Complete the OAuth flow AS THE BOT — not as yourself."
note "Keep it local-scoped. In a committed .mcp.json each teammate would"
note "authenticate as themselves, silently breaking the identity separation."
note "If you ever re-authenticate it (e.g. via /mcp), sign in as the bot again:"
note "the pipeline checks the identity at every cold start and holds its writes"
note "if the entry has drifted to someone else."
pause "Press Enter once the entry is authenticated"
ask LINEAR_MCP_SERVER "MCP server entry name [linear-bot]:"
[[ -n "$LINEAR_MCP_SERVER" ]] || LINEAR_MCP_SERVER="linear-bot"
write_env LINEAR_MCP_SERVER "$LINEAR_MCP_SERVER"
if command -v claude >/dev/null 2>&1; then
  if claude mcp list 2>/dev/null | grep -q "$LINEAR_MCP_SERVER"; then
    say "✓ '$LINEAR_MCP_SERVER' is registered"
  else
    warn "'$LINEAR_MCP_SERVER' did not appear in 'claude mcp list'."
    SKIPPED+=("verify the MCP entry '$LINEAR_MCP_SERVER' is registered and authenticated")
  fi
fi

# ── 6 ─────────────────────────────────────────────────────────────────────
stage "Install the agents and the skill"
INSTALL=yes
if [[ -d "$SKILL_DST" ]]; then
  warn "The pipeline is already installed here; files will be overwritten."
  confirm "Overwrite with the current framework version?" || INSTALL=no
fi

if [[ "$INSTALL" == no ]]; then
  say "Left as-is — no files copied."
  SKIPPED+=("framework files not updated from $FRAMEWORK_REPO")
else
  mkdir -p "$TARGET_REPO/.claude/agents" "$SKILL_DST"
  cp "$FRAMEWORK_REPO"/.claude/agents/pipeline-*.md "$TARGET_REPO/.claude/agents/"
  cp -R "$SKILL_SRC"/. "$SKILL_DST/"
  if [[ -f "$FRAMEWORK_REPO/examples/config.example.json" ]]; then
    cp "$FRAMEWORK_REPO/examples/config.example.json" "$SKILL_DST/config.example.json"
  fi
  find "$TARGET_REPO/.claude/agents" "$SKILL_DST" \( -name '*:Zone.Identifier' -o -name '*.pyc' \) -delete 2>/dev/null || true
  find "$SKILL_DST" -type d -name '__pycache__' -prune -exec rm -rf {} + 2>/dev/null || true
  chmod +x "$SKILL_DST"/scripts/*.py
  say "✓ 5 agents → .claude/agents/"
  say "✓ skill, ADRs, CONTEXT.md, config.md, config.example.json, scripts → .claude/skills/linear-pipeline/"
fi

if [[ "$INSTALL" == yes && "$LINEAR_MCP_SERVER" != "linear-bot" ]]; then
  sed -i.bak "s/mcp__linear-bot__/mcp__${LINEAR_MCP_SERVER}__/g" "$SKILL_DST/SKILL.md" && rm -f "$SKILL_DST/SKILL.md.bak"
  say "✓ rewrote the allowlist for entry '$LINEAR_MCP_SERVER'"
fi
if grep -q 'mcp__claude_ai_Linear__' "$SKILL_DST/SKILL.md" 2>/dev/null; then
  warn "the operator's Linear connection appears in the allowlist — remove it"
fi

# ── 7 ─────────────────────────────────────────────────────────────────────
stage "Keep the pipeline's runtime files out of git"
say "The pipeline writes run state, per-issue working material, caches and"
say "worktrees inside the repository. None of it belongs in a commit."
printf '\n'
GITIGNORE="$TARGET_REPO/.gitignore"
touch "$GITIGNORE"
ADDED=0
for rule in \
  ".agent/state.json" ".agent/state.json.tmp" ".agent/queue.json" ".agent/lock" \
  ".agent/triage.json" ".agent/cache/" ".issues/" ".claude/worktrees/" \
  "__pycache__/" "$ENV_FILE"; do
  if ! grep -qxF "$rule" "$GITIGNORE"; then
    if (( ADDED == 0 )); then printf '\n# Linear pipeline runtime files\n' >> "$GITIGNORE"; fi
    printf '%s\n' "$rule" >> "$GITIGNORE"
    ADDED=$((ADDED + 1))
  fi
done
if (( ADDED )); then say "✓ added $ADDED rule(s) to .gitignore"; else say "✓ .gitignore already covers the pipeline"; fi
note ".agent/config.json stays tracked: it is the team's shared configuration."
note "If setup mode later picks a worktree directory other than .claude/worktrees/,"
note "add that directory too."

# ── 8 ─────────────────────────────────────────────────────────────────────
stage "Concurrency and per-slot databases (optional)"
say "By default the pipeline works one issue at a time (limits.maxConcurrent: 1)."
say "Running several at once needs every verify entry that touches a database to"
say "get its own database per slot, so two gates never migrate the same tables."
printf '\n'
note "Skip this unless you plan to raise maxConcurrent. Setup mode will ask."
note "The shipped adapter, scripts/slot_db.py, is for a LOCAL Postgres and needs"
note "psql, pg_dump and pg_restore on PATH (Postgres 13 or later)."
if command -v psql >/dev/null 2>&1 && command -v pg_dump >/dev/null 2>&1 && command -v pg_restore >/dev/null 2>&1; then
  say "✓ psql, pg_dump and pg_restore found"
else
  note "psql, pg_dump or pg_restore not found; only needed for per-slot databases."
fi
note "After setup mode writes a database block, build the template once:"
note "  python3 .claude/skills/linear-pipeline/scripts/slot_db.py template"

# ── 9 ─────────────────────────────────────────────────────────────────────
stage "Verify the ticket fetch end to end"
say "This is the one path nothing else exercises: a real key against a real issue."
printf '\n'
ask VERIFY_ISSUE "An issue identifier the bot can see (e.g. ENG-123):"
if [[ -z "$VERIFY_ISSUE" ]]; then
  SKIPPED+=("run scripts/fetch_issue.py once to verify the API key")
else
  _out=$(mktemp)
  _rc=0
  LINEAR_API_KEY="$LINEAR_API_KEY" python3 "$SKILL_DST/scripts/fetch_issue.py" "$VERIFY_ISSUE" "$_out" || _rc=$?
  if (( _rc == 0 )); then
    say "✓ fetched — first lines:"
    sed -n '1,4p' "$_out" | while IFS= read -r l; do note "  $l"; done
  else
    warn "fetch failed (exit $_rc). 3=no key, 2=key cannot see it, 5=unreachable."
    SKIPPED+=("re-run scripts/fetch_issue.py once the key or issue is sorted")
  fi
  rm -f "$_out"
fi

finish

printf '  %sNext:%s run %s/linear-pipeline%s in %s\n' "$BOLD" "$RESET" "$BLUE" "$RESET" "$TARGET_REPO"
printf '  %sIt enters setup mode, detects your verify commands, base branch,%s\n' "$DIM" "$RESET"
printf '  %sworktree location and branch prefix, then writes .agent/config.json.%s\n' "$DIM" "$RESET"
printf '\n  %sWhen it asks for the Linear bot user, the answer is:%s %s\n' "$DIM" "$RESET" "$LINEAR_BOT_USER"
printf '  %sand for the MCP server entry:%s %s\n' "$DIM" "$RESET" "$LINEAR_MCP_SERVER"
printf '\n  %sAfter setup, start runs with%s %s/loop /linear-pipeline%s %sso the fallback wake%s\n' "$DIM" "$RESET" "$BLUE" "$RESET" "$DIM" "$RESET"
printf '  %s(ScheduleWakeup) can restart a run whose agent was interrupted.%s\n\n' "$DIM" "$RESET"
